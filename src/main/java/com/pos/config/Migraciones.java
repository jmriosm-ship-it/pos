package com.pos.config;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Deja la base de datos lista al arrancar: crea las tablas que falten (db/schema_postgres.sql) y, la primera vez,
 * pone los datos iniciales (roles, nombre del negocio y permisos de cada rol). Se puede ejecutar todas las veces
 * que haga falta: lo que ya existe no se toca.
 *
 * Para cambios futuros del esquema (una columna nueva, por ejemplo) se agregan abajo sentencias como
 *     ALTER TABLE productos ADD COLUMN IF NOT EXISTS algo VARCHAR(40);
 */
public class Migraciones {

    private Migraciones() {
    }

    // Cambios posteriores al esquema inicial. Cada uno debe poder repetirse sin dañar nada.
    private static final String[] CAMBIOS = {
            // Ventas hechas sin conexión: su identificador único evita subirlas dos veces.
            "ALTER TABLE ventas ADD COLUMN IF NOT EXISTS origen_offline VARCHAR(60)",
            "CREATE UNIQUE INDEX IF NOT EXISTS ux_ventas_origen_offline ON ventas (origen_offline) WHERE origen_offline IS NOT NULL",
            // Compras con pago a plazo: lo que se ha pagado (nulo = compras de antes, que se dan por pagadas) y los pagos a proveedores.
            "ALTER TABLE compras ADD COLUMN IF NOT EXISTS pagado NUMERIC(12,2)",
            "CREATE TABLE IF NOT EXISTS abonos_compra (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "id_compra INTEGER NOT NULL REFERENCES compras (id), id_usuario INTEGER NOT NULL REFERENCES usuarios (id), "
                    + "id_caja INTEGER REFERENCES cajas (id), metodo VARCHAR(30) NOT NULL, monto NUMERIC(12,2) NOT NULL, "
                    + "fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)",
            "CREATE INDEX IF NOT EXISTS ix_abonos_compra_compra ON abonos_compra (id_compra)",
            "CREATE INDEX IF NOT EXISTS ix_abonos_compra_caja ON abonos_compra (id_caja)",
    };

    public static void aplicar() throws SQLException {
        try (Connection con = Conexion.obtener(); Statement st = con.createStatement()) {
            // Si el esquema ya está al día no se repite todo (ejecutarlo entero tarda ~3 segundos con la base en internet).
            // La versión se calcula del propio esquema: cualquier cambio en él o en CAMBIOS la renueva sola.
            String esquema = leerEsquema();
            String version = Integer.toHexString((esquema + String.join("", CAMBIOS)).hashCode());
            if (version.equals(versionGuardada(st))) {
                return;
            }
            st.execute(esquema);
            for (String cambio : CAMBIOS) {
                st.execute(cambio);
            }

            // Datos iniciales: solo la primera vez (cuando todavía no hay roles).
            boolean primeraVez;
            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM roles")) {
                rs.next();
                primeraVez = rs.getInt(1) == 0;
            }
            if (primeraVez) {
                st.execute("INSERT INTO roles (id, nombre) VALUES (1, 'ADMIN'), (2, 'CAJERO'), (3, 'BODEGUERO')");
                st.execute("SELECT setval(pg_get_serial_sequence('roles', 'id'), 3)");
                st.execute("INSERT INTO configuracion (clave, valor) VALUES "
                        + "('negocio_nombre', 'LOURYX'), ('negocio_nit', '1092732537'), ('negocio_telefono', '324 736 2985'), "
                        + "('negocio_titular', 'Julián Darío Picón Durán'), ('negocio_actividad', 'Perfumería'), ('negocio_ciudad', 'Colombia'), "
                        + "('negocio_correo', 'julianpicon07.8@gmail.com'), ('recibo_pie', '¡Gracias por su compra!'), "
                        + "('impresora_nombre', ''), ('impresora_ancho_mm', '80') ON CONFLICT (clave) DO NOTHING");
                sembrar(st, "CAJERO", "DASHBOARD", "VENTAS", "CAJA", "CLIENTES");
                sembrar(st, "BODEGUERO", "DASHBOARD", "PRODUCTOS", "CATEGORIAS_PROVEEDORES", "INVENTARIO");
            }
            st.execute("INSERT INTO configuracion (clave, valor) VALUES ('esquema_version', '" + version + "') "
                    + "ON CONFLICT (clave) DO UPDATE SET valor = EXCLUDED.valor");
        }
    }

    private static String versionGuardada(Statement st) {
        try (java.sql.ResultSet rs = st.executeQuery("SELECT valor FROM configuracion WHERE clave = 'esquema_version'")) {
            return rs.next() ? rs.getString(1) : null;
        } catch (SQLException e) {
            return null;   // la tabla todavía no existe: es la primera vez
        }
    }

    // Da a un rol acceso a esos módulos y, en los que tienen acciones, el permiso de crear (los valores son fijos del programa).
    private static void sembrar(Statement st, String rol, String... modulos) throws SQLException {
        for (String modulo : modulos) {
            st.execute("INSERT INTO permisos_rol (id_rol, modulo) SELECT id, '" + modulo + "' FROM roles WHERE nombre = '" + rol
                    + "' ON CONFLICT DO NOTHING");
            if (!modulo.equals("DASHBOARD")) {
                st.execute("INSERT INTO permisos_accion (id_rol, modulo, accion) SELECT id, '" + modulo + "', 'CREAR' FROM roles "
                        + "WHERE nombre = '" + rol + "' ON CONFLICT DO NOTHING");
            }
        }
    }

    private static String leerEsquema() throws SQLException {
        try (InputStream in = Migraciones.class.getResourceAsStream("/db/schema_postgres.sql")) {
            if (in == null) {
                throw new SQLException("No se encontró el esquema de la base de datos (db/schema_postgres.sql).");
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new SQLException("No se pudo leer el esquema de la base de datos: " + e.getMessage(), e);
        }
    }
}
