-- Esquema de Sistema SAS para PostgreSQL (Supabase). Se puede ejecutar varias veces: no repite nada.

CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    usuario VARCHAR(30) NOT NULL,
    clave_hash VARCHAR(100) NOT NULL,
    id_rol INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cupo NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    pago_dia NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    puede_anular BOOLEAN NOT NULL DEFAULT FALSE,
    puede_editar_productos BOOLEAN NOT NULL DEFAULT TRUE,
    descuento_max INTEGER NOT NULL DEFAULT 100,
    PRIMARY KEY (id),
    UNIQUE (usuario),
    CONSTRAINT usuarios_ibfk_1 FOREIGN KEY (id_rol) REFERENCES roles (id)
);

CREATE TABLE IF NOT EXISTS configuracion (
    clave VARCHAR(50) NOT NULL,
    valor VARCHAR(255) DEFAULT NULL,
    PRIMARY KEY (clave)
);

CREATE TABLE IF NOT EXISTS categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(60) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS proveedores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) DEFAULT NULL,
    correo VARCHAR(100) DEFAULT NULL,
    direccion VARCHAR(150) DEFAULT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    documento VARCHAR(30) DEFAULT NULL,
    telefono VARCHAR(20) DEFAULT NULL,
    correo VARCHAR(100) DEFAULT NULL,
    direccion VARCHAR(150) DEFAULT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE (documento)
);

CREATE TABLE IF NOT EXISTS cajas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INTEGER NOT NULL,
    abierta_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cerrada_en TIMESTAMP DEFAULT NULL,
    monto_inicial NUMERIC(12,2) NOT NULL,
    monto_esperado NUMERIC(12,2) DEFAULT NULL,
    monto_contado NUMERIC(12,2) DEFAULT NULL,
    diferencia NUMERIC(12,2) DEFAULT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'ABIERTA',
    PRIMARY KEY (id),
    CONSTRAINT cajas_ibfk_1 FOREIGN KEY (id_usuario) REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS productos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    id_categoria INTEGER DEFAULT NULL,
    id_proveedor INTEGER DEFAULT NULL,
    precio_compra NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    precio_venta NUMERIC(12,2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    marca VARCHAR(60) DEFAULT NULL,
    condicion VARCHAR(20) NOT NULL DEFAULT 'Nuevo',
    garantia_dias INTEGER NOT NULL DEFAULT 0,
    por_imei BOOLEAN NOT NULL DEFAULT FALSE,
    capacidad VARCHAR(30) DEFAULT NULL,
    color VARCHAR(30) DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE (codigo),
    CONSTRAINT productos_ibfk_1 FOREIGN KEY (id_categoria) REFERENCES categorias (id),
    CONSTRAINT productos_ibfk_2 FOREIGN KEY (id_proveedor) REFERENCES proveedores (id)
);

CREATE TABLE IF NOT EXISTS ventas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_caja INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    id_cliente INTEGER DEFAULT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal NUMERIC(12,2) NOT NULL,
    descuento NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total NUMERIC(12,2) NOT NULL,
    metodo_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'COMPLETADA',
    descuento_promo NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    descuento_puntos NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    puntos_usados INTEGER NOT NULL DEFAULT 0,
    puntos_ganados INTEGER NOT NULL DEFAULT 0,
    etiqueta VARCHAR(20) DEFAULT NULL,
    financiera_nombre VARCHAR(80) DEFAULT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ventas_ibfk_1 FOREIGN KEY (id_caja) REFERENCES cajas (id),
    CONSTRAINT ventas_ibfk_2 FOREIGN KEY (id_usuario) REFERENCES usuarios (id),
    CONSTRAINT ventas_ibfk_3 FOREIGN KEY (id_cliente) REFERENCES clientes (id)
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_venta INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unit NUMERIC(12,2) NOT NULL,
    costo_unit NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    imeis VARCHAR(600) DEFAULT NULL,
    precio_original NUMERIC(12,2) DEFAULT NULL,
    PRIMARY KEY (id),
    CONSTRAINT detalle_venta_ibfk_1 FOREIGN KEY (id_venta) REFERENCES ventas (id),
    CONSTRAINT detalle_venta_ibfk_2 FOREIGN KEY (id_producto) REFERENCES productos (id)
);

CREATE TABLE IF NOT EXISTS pagos_venta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_venta INTEGER NOT NULL,
    metodo VARCHAR(30) NOT NULL,
    monto NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT pagos_venta_ibfk_1 FOREIGN KEY (id_venta) REFERENCES ventas (id)
);

CREATE TABLE IF NOT EXISTS producto_imeis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_producto INTEGER NOT NULL,
    imei VARCHAR(20) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE',
    id_venta INTEGER DEFAULT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE (imei),
    CONSTRAINT producto_imeis_ibfk_1 FOREIGN KEY (id_producto) REFERENCES productos (id)
);

CREATE TABLE IF NOT EXISTS compras (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_proveedor INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(12,2) NOT NULL,
    anulada BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_anulacion TIMESTAMP DEFAULT NULL,
    motivo_anulacion VARCHAR(200) DEFAULT NULL,
    PRIMARY KEY (id),
    CONSTRAINT compras_ibfk_1 FOREIGN KEY (id_proveedor) REFERENCES proveedores (id),
    CONSTRAINT compras_ibfk_2 FOREIGN KEY (id_usuario) REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS detalle_compra (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_compra INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    costo_unit NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT detalle_compra_ibfk_1 FOREIGN KEY (id_compra) REFERENCES compras (id),
    CONSTRAINT detalle_compra_ibfk_2 FOREIGN KEY (id_producto) REFERENCES productos (id)
);

CREATE TABLE IF NOT EXISTS movimientos_inventario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
