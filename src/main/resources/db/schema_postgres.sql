-- Seguridad en Supabase: las tablas del esquema "public" quedan expuestas por su API pública. Con RLS activado y sin
-- políticas, esa API no puede leer ni escribir nada; el programa entra directo a la base de datos con su propio usuario,
-- que no se ve afectado. Se repite en cada arranque para cubrir también las tablas nuevas.
DO $$
DECLARE t text;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated';
    END IF;
END $$;
